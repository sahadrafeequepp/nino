"""Abstract VisionAdapter interface for Nino's on-device vision pipeline."""

from abc import ABC, abstractmethod


class VisionAdapter(ABC):
    """Abstract base class for vision-language model adapters."""

    @abstractmethod
    async def describe_image(
        self,
        image_data: bytes,
        prompt: str = "Describe what you see in this image in detail.",
    ) -> str:
        """Analyze image data and return a descriptive natural language summary.

        Args:
            image_data: Raw image bytes (PNG, JPEG, WEBP, etc.)
            prompt: Question or instruction guiding the vision model analysis.

        Returns:
            A descriptive textual summary generated by the model.
        """
        pass

    @abstractmethod
    async def extract_text(self, image_data: bytes) -> str:
        """Identify and transcribe any text visible within the image.

        Args:
            image_data: Raw image bytes.

        Returns:
            Extracted text string verbatim, or an empty string if no text is present.
        """
        pass
